"""Actual cross-repository draft geometry + Engine presentation event receipts.

LFXV1 = generated by LevelDraftVisualHandoff from real validated LevelDraft.
M3P1 = generated by NeutralVisualReceiptCodec from real Engine
PresentationEvent objects, NOT a fabricated match simulator.

Both are READ-ONLY intermediary evidence. Event-source authentication,
settled ReplayCodec/ENG-M24 parity, runtime navigation, owner artwork rights
and game reward/score authorization are independent, still-open gates.
"""
from __future__ import annotations

import base64
import hashlib
import json
import re
from dataclasses import dataclass
from typing import Any

STAGE = "LFXV1_VALIDATED_DRAFT_NOT_ENGINE_REPLAY"
M3P1 = "M3P1"
PROFILES = ("Coral_Rescue", "Garage_Legends", "Dino_Islands",
            "The_Fractured_Realms", "Wonder_Pop")
SHA256 = re.compile(r"[0-9a-f]{64}\Z")
MAX_EVENTS = 2048
MAX_BYTES = 1_048_576
# M3P1 enum ordinals are source-pinned to actual Engine
# PresentationEventKind. Swap has NO prior M07 animation key.
EVENT_CUES = {0: None, 1: "tile_match", 2: "special_trigger",
              3: "special_trigger", 4: "special_trigger",
              5: "combo_chain", 6: "tile_spawn"}
AUTH_FALSE = ("actualSdkWinVerified", "engineM24ReleaseAccepted",
              "realPlayableLevel", "assetRightsApproved", "releaseAllowed")


class CrossFactoryError(ValueError):
    pass


def _strict_json(data: bytes) -> Any:
    if not isinstance(data, bytes) or not 0 < len(data) <= 2_000_000:
        raise CrossFactoryError("missing/oversized UTF8 LFXV1 source")
    def unique(items):
        obj = {}
        for key, value in items:
            if key in obj:
                raise CrossFactoryError("duplicate JSON field")
            obj[key] = value
        return obj
    try:
        return json.loads(data.decode("utf-8", errors="strict"),
                          object_pairs_hook=unique,
                          parse_constant=lambda _: (_ for _ in ()).throw(
                              CrossFactoryError("nonfinite JSON")))
    except (UnicodeError, ValueError) as exc:
        raise CrossFactoryError("invalid UTF8/JSON") from exc


def _int(value, minimum, maximum):
    return type(value) is int and minimum <= value <= maximum


def read_lfxv1(data: bytes, expected_profile: str | None = None) -> dict:
    value = _strict_json(data)
    keys = {"schemaVersion", "stage", "gameProfileId", "levelId",
            "width", "height", "layers", "moveBudget", "seed",
            "sourceDraftSha256", "sourceLevelFactoryGitSha",
            "cells", "goals", *AUTH_FALSE}
    if not isinstance(value, dict) or set(value) != keys:
        raise CrossFactoryError("LFXV1 field set/version mismatch")
    if (value["schemaVersion"] != 1 or type(value["schemaVersion"]) is not int or
            value["stage"] != STAGE or value["gameProfileId"] not in PROFILES or
            (expected_profile is not None and value["gameProfileId"] != expected_profile) or
            not isinstance(value["levelId"], str) or not 1 <= len(value["levelId"]) <= 128 or
            not _int(value["width"], 1, 32) or
            not _int(value["height"], 1, 32) or
            not _int(value["layers"], 1, 4) or
            not _int(value["moveBudget"], 1, 999) or
            not _int(value["seed"], 0, 2**63-1)):
        raise CrossFactoryError("unsupported LFX v1 profile/geometry/seed")
    if (not isinstance(value["sourceDraftSha256"], str) or
            not SHA256.fullmatch(value["sourceDraftSha256"]) or
            value["sourceLevelFactoryGitSha"] != "UNPINNED"):
        raise CrossFactoryError("LFX source digest or unverified Git pin spoofed")
    if any(value[f] is not False for f in AUTH_FALSE):
        raise CrossFactoryError("forged final Engine/game/rights status")
    expected = value["width"] * value["height"] * value["layers"]
    if not isinstance(value["cells"], list) or len(value["cells"]) != expected:
        raise CrossFactoryError("incomplete LFX grid")
    keys_cell = {"row","column","layer","active","locked","contentId",
                 "obstacleId","specialId","obstacleDurability","lockDurability"}
    positions = set()
    for c in value["cells"]:
        if not isinstance(c, dict) or set(c) != keys_cell:
            raise CrossFactoryError("unknown/invalid LFX cell")
        r, col, layer = c["row"],c["column"],c["layer"]
        if not (_int(r,0,value["height"]-1) and
                _int(col,0,value["width"]-1) and
                _int(layer,0,value["layers"]-1)):
            raise CrossFactoryError("out-of-bounds cell")
        position=(layer,r,col)
        if position in positions:
            raise CrossFactoryError("duplicate LFX cell")
        positions.add(position)
        if type(c["active"]) is not bool or type(c["locked"]) is not bool:
            raise CrossFactoryError("invalid cell activity")
        if any(c[k] is not None and
               (not isinstance(c[k],str) or not 1 <= len(c[k]) <= 128)
               for k in ("contentId","obstacleId","specialId")):
            raise CrossFactoryError("invalid cell content identifier")
        if not _int(c["obstacleDurability"],0,99) or not _int(c["lockDurability"],0,99):
            raise CrossFactoryError("invalid LFX obstacle durability")
        if (not c["active"] and (c["locked"] or c["contentId"] is not None or
                c["obstacleId"] is not None or c["specialId"] is not None or
                c["obstacleDurability"] != 0 or c["lockDurability"] != 0)):
            raise CrossFactoryError("hole contains forbidden occupant")
        if c["active"] and c["contentId"] is None and c["obstacleId"] is None:
            raise CrossFactoryError("active cell without content/obstacle")
    if not isinstance(value["goals"],list) or not 1<=len(value["goals"])<=32:
        raise CrossFactoryError("goals must be declared")
    goal_ids=set()
    for g in value["goals"]:
        if (not isinstance(g,dict) or
                set(g)!={"goalId","targetId","targetCount"} or
                not isinstance(g["goalId"],str) or
                not isinstance(g["targetId"],str) or
                not 1<=len(g["goalId"])<=128 or
                not 1<=len(g["targetId"])<=128 or
                not _int(g["targetCount"],1,99999) or
                g["goalId"] in goal_ids):
            raise CrossFactoryError("invalid or duplicate LFX goal")
        goal_ids.add(g["goalId"])
    return value


def _decode_b64(encoded: str) -> str:
    try:
        raw = base64.b64decode(encoded,validate=True)
        if base64.b64encode(raw).decode("ascii") != encoded:
            raise CrossFactoryError("noncanonical base64")
        value = raw.decode("utf-8",errors="strict")
        if not value.strip() or len(value)>256:
            raise CrossFactoryError("bad Engine event string")
        return value
    except (ValueError, UnicodeError) as exc:
        raise CrossFactoryError("invalid event UTF8/base64") from exc


def read_m3p1(data: bytes, expected_profile: str) -> list[dict]:
    if (expected_profile not in PROFILES or not isinstance(data, bytes) or
            not 0 < len(data) <= MAX_BYTES):
        raise CrossFactoryError("missing/oversized Engine wire/profile")
    try:
        text=data.decode("utf-8",errors="strict")
    except UnicodeError as e:
        raise CrossFactoryError("invalid Engine UTF8") from e
    lines=text.split("\n")
    if (len(lines)<4 or lines[0]!=M3P1 or lines[1]!=expected_profile or
            not re.fullmatch(r"(0|[1-9][0-9]*)",lines[2])):
        raise CrossFactoryError("Engine M3P1 schema/profile/count mismatch")
    count=int(lines[2])
    if count>MAX_EVENTS or len(lines)!=count+4:
        raise CrossFactoryError("Engine event count inconsistent")
    expected_checksum=hashlib.sha256(("\n".join(lines[:-1])+"\n").encode()).hexdigest()
    if expected_checksum != lines[-1]:
        raise CrossFactoryError("Engine receipt SHA256 mismatch")
    events=[]
    for i in range(count):
        col=lines[3+i].split("|")
        if len(col)!=6 or col[0]!=str(i+1) or col[2] not in ("0","1","2","3","4","5","6") or col[4] not in ("0","1","2"):
            raise CrossFactoryError("Engine sequence/kind/intensity invalid")
        ident,key=_decode_b64(col[1]),_decode_b64(col[3])
        coordinates=[]
        for token in col[5].split(","):
            m=re.fullmatch(r"(0|[1-9][0-9]*):(0|[1-9][0-9]*):(0|[1-9][0-9]*)",token)
            if not m:
                raise CrossFactoryError("invalid canonical Engine coordinate")
            position=tuple(int(n) for n in m.groups())
            if position in coordinates or max(position)>1024:
                raise CrossFactoryError("duplicate/excessive Engine board position")
            coordinates.append(position)
        if not 1<=len(coordinates)<=1024 or coordinates!=sorted(coordinates):
            raise CrossFactoryError("Engine positions out of order")
        events.append({"sequence":i+1,"eventId":ident,"presentationKey":key,
                       "kind":int(col[2]),"intensity":int(col[4]),
                       "positions":coordinates,"vufCue":EVENT_CUES[int(col[2])]})
    return events


def bind_readonly(level: dict, events: list[dict], *, source_sha: str) -> dict:
    if (not isinstance(source_sha,str) or not SHA256.fullmatch(source_sha) or
            not isinstance(level,dict) or level.get("stage")!=STAGE or
            not isinstance(events,list)):
        raise CrossFactoryError("missing source attestation")
    for e in events:
        if not isinstance(e,dict) or not isinstance(e.get("positions"),list):
            raise CrossFactoryError("unverified Engine event")
        for layer,row,column in e["positions"]:
            if layer>=level["layers"] or row>=level["height"] or column>=level["width"]:
                raise CrossFactoryError("Engine event outside LFX source geometry")
    return {
        "stage":"THREE_FACTORY_SOURCE_CONTRACT_ONLY",
        "profileId":level["gameProfileId"],
        "levelId":level["levelId"],
        "levelSourceSha256":level["sourceDraftSha256"],
        "engineM3p1Sha256":source_sha,
        "actualLfxDraftGeometry":True,
        "actualEngineTypedEventsWireParsed":True,
        "eventCount":len(events),
        "unboundSwapEvents":sum(e["vufCue"] is None for e in events),
        "mappedPresentationCues":[e["vufCue"] for e in events],
        "authoritativeEventOriginAuthenticated":False,
        "engineSdkSettledSnapshotsChecked":False,
        "levelFactoryEngineM24Approved":False,
        "actualVisualAssetsLoaded":False,
        "realGameplayReplayValidated":False,
        "ownerArtApproved":False,
        "releaseAllowed":False,
    }
